proptest! {
    /// An arbitrary recording length and an arbitrary interleaving of
    /// acknowledgements and window supplies: what the client reassembles is the
    /// recording exactly, and no window outside `[0, total)` is ever asked for.
    ///
    /// The waits are what make it an interleaving rather than a script — a
    /// supplier that answers on the third pass rather than the first must lose
    /// no byte and no place.
    #[test]
    fn a_recording_is_delivered_exactly_however_the_supplies_interleave(
        total in 0u64..(3 * WINDOW_LEN as u64),
        waits in prop::collection::vec(0usize..3, 1..8),
    ) {
        let recording = Recording(total);
        let mut endpoint = streaming_endpoint();
        let mut station = Station::new(40000, 0x0f0f_0001);
        let mut out = vec![0u8; ROOMY];
        handshake(&mut endpoint, &mut station, &mut out);
        let mut transfer = Transfer::begin(&mut endpoint, &mut station, &get(RECORDING_TARGET));

        let mut waits = waits.into_iter().cycle();
        let mut hold = waits.next().unwrap_or(0);
        let mut supplied = 0u64;
        for _ in 0..8192 {
            if endpoint.pending_stream().is_some() {
                prop_assert!(endpoint.begin_stream(total, ContentType::OctetStream));
            }
            if let Some((_, start, len)) = endpoint.window_wanted() {
                prop_assert!(
                    start < total,
                    "a window at {start} of a {total}-byte recording"
                );
                if hold == 0 {
                    prop_assert!(endpoint.supply_window(start, &recording.window(start, len)));
                    supplied += 1;
                    hold = waits.next().unwrap_or(0);
                } else {
                    hold -= 1;
                }
            }
            transfer.drain(&mut endpoint);
            if transfer.answered.closed {
                break;
            }
            transfer.acknowledge(&mut endpoint);
        }
        prop_assert!(transfer.answered.closed, "{total} bytes never finished");
        let (head, body) = transfer.answered.split();
        let stated = format!("Content-Length: {total}\r\n");
        prop_assert!(head.contains(&stated));
        let expected = recording.bytes();
        prop_assert_eq!(body, expected.as_slice());
        prop_assert_eq!(supplied, recording.windows());
        prop_assert_eq!(endpoint.http_counters().windows_refused, 0);
        prop_assert_eq!(endpoint.http_counters().streams_abandoned, 0);
        prop_assert_eq!(endpoint.http_counters().retransmits_unavailable, 0);
    }
}

