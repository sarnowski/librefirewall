/// A body of `len` deterministic bytes, standing in for the metric exposition a
/// protection domain renders. Deterministic so a response can be compared to it
/// byte for byte, and sized by the caller so a test can pick one that spans one
/// segment or twenty.
#[derive(Clone, Copy, Debug)]
struct Body(usize);

impl Body {
    /// Write it into a caller's staging buffer, as the protection domain's own
    /// renderer does. `None` where it does not fit, which is the one thing about
    /// a body that is **ours** rather than a client's.
    fn render(self, out: &mut [u8]) -> Option<usize> {
        let target = out.get_mut(..self.0)?;
        for (index, byte) in target.iter_mut().enumerate() {
            *byte = b'a'.wrapping_add((index % 26) as u8);
        }
        Some(self.0)
    }

    fn bytes(self) -> Vec<u8> {
        let mut out = vec![0u8; self.0];
        self.render(&mut out).expect("its own length");
        out
    }
}

/// A body no staging buffer can hold, so the refusal path is reachable at all.
const UNRENDERABLE: Body = Body(usize::MAX);

/// The body every endpoint below serves unless it says otherwise: bigger than
/// one segment, so the ordinary case in these tests is the multi-segment one.
const BODY: Body = Body(4_000);

/// The target the endpoints below register as streamed. A path this crate knows
/// nothing about, deliberately: what is behind it is the owner's business.
const RECORDING_TARGET: &str = "/recordings/latest";

/// A body no array holds, standing in for a recording a protection domain reads
/// off a block device a window at a time.
///
/// Deterministic, so a delivered stream is compared to it byte for byte, and
/// generated by a rule whose period is coprime with [`WINDOW_LEN`] — a window
/// handed over at the wrong offset therefore produces different bytes rather
/// than the same ones shifted, which is the mistake worth catching.
#[derive(Clone, Copy, Debug)]
struct Recording(u64);

impl Recording {
    fn byte(at: u64) -> u8 {
        (at % 251) as u8
    }

    fn bytes(self) -> Vec<u8> {
        (0..self.0).map(Self::byte).collect()
    }

    /// The `len` bytes at `start`: exactly what
    /// [`Endpoint::window_wanted`] asked for, which is what a supplier that can
    /// read the whole span hands over.
    fn window(self, start: u64, len: usize) -> Vec<u8> {
        let end = start.saturating_add(len as u64).min(self.0);
        (start..end).map(Self::byte).collect()
    }

    /// Windows this recording is delivered in, and so how many supplies a whole
    /// transfer takes. The window slides by what it holds less the span it must
    /// keep behind for retransmission.
    fn windows(self) -> u64 {
        let stride = (WINDOW_LEN - RETRANSMIT_SPAN) as u64;
        if self.0 == 0 {
            return 0;
        }
        if self.0 <= WINDOW_LEN as u64 {
            return 1;
        }
        1 + (self.0 - WINDOW_LEN as u64).div_ceil(stride)
    }
}

fn endpoint() -> Endpoint {
    Endpoint::new(OUR_MAC, OUR_ADDRESS, PREFIX, secret()).expect("a unicast pair on a /24")
}

/// An endpoint that also answers [`RECORDING_TARGET`] by streaming.
fn streaming_endpoint() -> Endpoint {
    let mut endpoint = endpoint();
    assert!(endpoint.serve_stream_at(RECORDING_TARGET));
    endpoint
}

/// What a caller supplies between a request being counted and its answer going
/// out: the exposition rendered whole, or a recording delivered by window.
///
/// One value rather than two drivers, because the loop around it — poll until
/// the pass has nothing left, then let the peer's acknowledgement open the
/// window again — is the same either way and two copies of it would drift.
#[derive(Clone, Copy, Debug)]
enum Supply {
    Rendered(Body),
    Streamed(Recording),
    /// A recording read off a ring of extents this many bytes long: a supplier
    /// that cannot reach past the extent a window starts in, so every window
    /// crossing a boundary is handed over short. This is what a recorder reading
    /// a segmented block device does, and a short extent makes *every* window
    /// short.
    Segmented(Recording, u64),
}

impl Supply {
    /// One pass of the protection domain's own work.
    fn offer(self, endpoint: &mut Endpoint) {
        match self {
            Self::Rendered(body) => {
                if endpoint.body_wanted().is_some() {
                    endpoint.supply_body(Status::Ok, Some(ContentType::Metrics), |out| {
                        body.render(out)
                    });
                }
            }
            Self::Streamed(recording) => {
                if endpoint.pending_stream().is_some() {
                    assert!(
                        endpoint.begin_stream(recording.0, ContentType::OctetStream),
                        "the length was refused"
                    );
                }
                if let Some((_, start, len)) = endpoint.window_wanted() {
                    assert!(
                        endpoint.supply_window(start, &recording.window(start, len)),
                        "the window at {start} was refused"
                    );
                }
            }
            Self::Segmented(recording, extent) => {
                if endpoint.pending_stream().is_some() {
                    assert!(
                        endpoint.begin_stream(recording.0, ContentType::OctetStream),
                        "the length was refused"
                    );
                }
                if let Some((_, start, len)) = endpoint.window_wanted() {
                    // Everything to the end of the extent this window starts in,
                    // and no further.
                    let reach = extent - (start % extent);
                    // Lossless: bounded by `len`, itself a `usize`.
                    let short = (len as u64).min(reach) as usize;
                    assert!(
                        endpoint.supply_window(start, &recording.window(start, short)),
                        "the {short}-byte window at {start} was refused"
                    );
                }
            }
        }
    }
}

/// Supply whatever body the endpoint is waiting on, as the protection domain's
/// poll does between counting a request and answering it.
fn supply(endpoint: &mut Endpoint, body: Body) {
    Supply::Rendered(body).offer(endpoint);
}

/// An instant, built the way this crate's callers build one: a `Monotonic` is
/// only reachable through a `Calibration`.
fn at(nanos: u64) -> Monotonic {
    use core::num::NonZeroU64;
    use lfw_clock::{Calibration, Ticks};
    let hz = NonZeroU64::new(lfw_clock::NANOS_PER_SECOND).expect("a nonzero frequency");
    Calibration::new(hz, Ticks(0), 0).monotonic(Ticks(nanos))
}

/// An ARP request as a station puts one on the wire: broadcast, 42 bytes.
fn arp_request(
    destination: MacAddress,
    sender_mac: MacAddress,
    sender_address: Ipv4Address,
    target: Ipv4Address,
) -> Vec<u8> {
    let mut frame = Vec::new();
    frame.extend_from_slice(&destination.0);
    frame.extend_from_slice(&sender_mac.0);
    frame.extend_from_slice(&EtherType::ARP.0.to_be_bytes());
    frame.extend_from_slice(&1u16.to_be_bytes());
    frame.extend_from_slice(&EtherType::IPV4.0.to_be_bytes());
    frame.push(6);
    frame.push(4);
    frame.extend_from_slice(&1u16.to_be_bytes());
    frame.extend_from_slice(&sender_mac.0);
    frame.extend_from_slice(&sender_address.octets());
    frame.extend_from_slice(&[0; 6]);
    frame.extend_from_slice(&target.octets());
    frame
}

/// The request every ARP test below is one edit from.
fn arp() -> Vec<u8> {
    arp_request(
        MacAddress::BROADCAST,
        STATION_MAC,
        STATION_ADDRESS,
        OUR_ADDRESS,
    )
}

/// The RFC 1071 sum, written independently of the crate under test.
fn checksum(bytes: &[u8]) -> u16 {
    let mut sum = 0u32;
    for index in 0..bytes.len().div_ceil(2) {
        let high = bytes[index * 2];
        let low = bytes.get(index * 2 + 1).copied().unwrap_or(0);
        sum += u32::from(u16::from_be_bytes([high, low]));
    }
    while sum > 0xffff {
        sum = (sum & 0xffff) + (sum >> 16);
    }
    !(sum as u16)
}

/// One IPv4 frame as fields, so every test below edits exactly the field it is
/// about and the checksums are always right.
struct Datagram {
    destination_mac: MacAddress,
    source_mac: MacAddress,
    source: Ipv4Address,
    destination: Ipv4Address,
    protocol: Protocol,
    fragment_offset: u16,
    message_type: u8,
    code: u8,
    identifier: u16,
    sequence: u16,
    payload: Vec<u8>,
    /// Whether the ICMP checksum is the right one, so a corrupt message is a
    /// deliberate edit rather than a side effect of another.
    seal_icmp: bool,
}

impl Datagram {
    /// An echo request from the station to us: what the endpoint exists to
    /// answer.
    fn echo() -> Self {
        Self {
            destination_mac: OUR_MAC,
            source_mac: STATION_MAC,
            source: STATION_ADDRESS,
            destination: OUR_ADDRESS,
            protocol: Protocol::ICMP,
            fragment_offset: 0,
            message_type: 8,
            code: 0,
            identifier: 0x1234,
            sequence: 9,
            payload: b"echo-payload".to_vec(),
            seal_icmp: true,
        }
    }

    fn build(&self) -> Vec<u8> {
        let mut icmp = Vec::new();
        icmp.push(self.message_type);
        icmp.push(self.code);
        icmp.extend_from_slice(&[0, 0]);
        icmp.extend_from_slice(&self.identifier.to_be_bytes());
        icmp.extend_from_slice(&self.sequence.to_be_bytes());
        icmp.extend_from_slice(&self.payload);
        let sum = if self.seal_icmp {
            checksum(&icmp)
        } else {
            0x1234
        };
        icmp[2..4].copy_from_slice(&sum.to_be_bytes());

        let mut frame = Vec::new();
        frame.extend_from_slice(&self.destination_mac.0);
        frame.extend_from_slice(&self.source_mac.0);
        frame.extend_from_slice(&EtherType::IPV4.0.to_be_bytes());
        let mut ip = [0u8; IPV4_HEADER_LEN];
        ip[0] = 0x45;
        ip[2..4].copy_from_slice(&((IPV4_HEADER_LEN + icmp.len()) as u16).to_be_bytes());
        ip[6..8].copy_from_slice(&self.fragment_offset.to_be_bytes());
        ip[8] = 64;
        ip[9] = self.protocol.0;
        ip[12..16].copy_from_slice(&self.source.octets());
        ip[16..20].copy_from_slice(&self.destination.octets());
        let sum = checksum(&ip);
        ip[10..12].copy_from_slice(&sum.to_be_bytes());
        frame.extend_from_slice(&ip);
        frame.extend_from_slice(&icmp);
        frame
    }
}

/// Hand one frame to a fresh endpoint, with roomy storage.
fn handle(frame: &[u8]) -> (Outcome, Vec<u8>, EndpointCounters) {
    let mut endpoint = endpoint();
    let mut out = vec![0u8; ROOMY];
    let outcome = endpoint.handle(Some(at(0)), frame, &mut out);
    if let Some(len) = outcome.reply() {
        out.truncate(len);
    } else {
        out.clear();
    }
    (outcome, out, endpoint.counters())
}

#[test]
fn a_configured_pair_no_endpoint_can_answer_under_is_refused() {
    assert_eq!(
        Endpoint::new(MacAddress::BROADCAST, OUR_ADDRESS, PREFIX, secret()).err(),
        Some(EndpointError::MacNotUnicast {
            mac: MacAddress::BROADCAST
        })
    );
    assert_eq!(
        Endpoint::new(MacAddress([0; 6]), OUR_ADDRESS, PREFIX, secret()).err(),
        Some(EndpointError::MacNotUnicast {
            mac: MacAddress([0; 6])
        })
    );
    for octets in [
        [224, 0, 0, 1],
        [255, 255, 255, 255],
        [127, 0, 0, 1],
        [0, 0, 0, 0],
    ] {
        let address = Ipv4Address::from_octets(octets);
        assert_eq!(
            Endpoint::new(OUR_MAC, address, PREFIX, secret()).err(),
            Some(EndpointError::AddressNotUnicast { address })
        );
    }
    for prefix_length in [33u8, 64, 255] {
        assert_eq!(
            Endpoint::new(OUR_MAC, OUR_ADDRESS, prefix_length, secret()).err(),
            Some(EndpointError::PrefixLengthOutOfRange { prefix_length })
        );
    }
    let endpoint =
        Endpoint::new(OUR_MAC, OUR_ADDRESS, 32, secret()).expect("a host route is a prefix");
    assert_eq!(endpoint.mac(), OUR_MAC);
    assert_eq!(endpoint.address(), OUR_ADDRESS);
    assert_eq!(endpoint.prefix_length(), 32);
    assert_eq!(endpoint.counters(), EndpointCounters::new());
    assert_eq!(EndpointCounters::default(), EndpointCounters::new());
}

#[test]
fn an_arp_request_for_our_address_is_answered_with_our_mac() {
    let (outcome, reply, counters) = handle(&arp());
    assert_eq!(outcome, Outcome::ArpReply { len: ARP_FRAME_LEN });
    assert_eq!(counters.arp_replies, 1);
    assert_eq!(counters.replies(), 1);
    assert_eq!(counters.total(), 1);

    let ethernet = Ethernet::parse(&reply).expect("a reply is a frame");
    assert_eq!(ethernet.header.destination, STATION_MAC);
    assert_eq!(ethernet.header.source, OUR_MAC);
    assert_eq!(ethernet.header.ether_type, EtherType::ARP);
    let packet = ArpPacket::parse(ethernet.payload).expect("an ARP packet");
    assert_eq!(packet.operation, ArpOperation::Reply);
    assert_eq!(packet.sender_mac, OUR_MAC);
    assert_eq!(packet.sender_address, OUR_ADDRESS);
    assert_eq!(packet.target_mac, STATION_MAC);
    assert_eq!(packet.target_address, STATION_ADDRESS);
}

