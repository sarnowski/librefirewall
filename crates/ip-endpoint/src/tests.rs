/// A scripted TCP station on the management port: it composes whole frames and
/// reads back whole frames, so the exchange below is the one that crosses a wire.
struct Station {
    port: u16,
    next: lfw_tcp::SeqNumber,
    expect: lfw_tcp::SeqNumber,
    window: u16,
}

impl Station {
    fn new(port: u16, iss: u32) -> Self {
        Self {
            port,
            next: lfw_tcp::SeqNumber::new(iss),
            expect: lfw_tcp::SeqNumber::new(0),
            window: 4096,
        }
    }

    /// A frame carrying one segment from this station.
    fn frame(&mut self, flags: lfw_tcp::Flags, payload: &[u8]) -> Vec<u8> {
        let mut out = vec![0u8; ROOMY];
        let syn = flags.contains(lfw_tcp::Flags::SYN);
        let len = lfw_tcp::Outgoing {
            source_port: self.port,
            destination_port: MANAGEMENT_PORT,
            sequence: self.next,
            acknowledgement: self.expect,
            flags,
            window: self.window,
            mss: syn.then_some(TCP_MSS),
            window_scale: None,
            payload,
        }
        .write(
            STATION_ADDRESS,
            OUR_ADDRESS,
            out.get_mut(Ipv4Frame::PAYLOAD_AT..).expect("room"),
        )
        .expect("room for a segment");
        let total = Ipv4Frame {
            destination_mac: OUR_MAC,
            source_mac: STATION_MAC,
            source: STATION_ADDRESS,
            destination: OUR_ADDRESS,
            protocol: Protocol::TCP,
        }
        .write(&mut out, len)
        .expect("room for a frame");
        out.truncate(total);
        // Lossless: a payload here is far below 2^32.
        let occupied =
            payload.len() as u32 + u32::from(syn) + u32::from(flags.contains(lfw_tcp::Flags::FIN));
        self.next = self.next.add(occupied);
        out
    }

    /// Read a frame the endpoint sent, learning what to acknowledge from it and
    /// answering its segment's fields.
    fn read(&mut self, frame: &[u8]) -> (lfw_tcp::Flags, lfw_tcp::SeqNumber, Vec<u8>) {
        let ethernet = Ethernet::parse(frame).expect("a frame");
        assert_eq!(ethernet.header.source, OUR_MAC);
        assert_eq!(ethernet.header.destination, STATION_MAC);
        assert_eq!(ethernet.header.ether_type, EtherType::IPV4);
        let packet = Ipv4Packet::parse(ethernet.payload).expect("a datagram");
        assert_eq!(packet.header().protocol, Protocol::TCP);
        assert_eq!(packet.header().source, OUR_ADDRESS);
        assert_eq!(packet.header().destination, STATION_ADDRESS);
        let segment = lfw_tcp::Segment::parse(OUR_ADDRESS, STATION_ADDRESS, packet.payload())
            .expect("a segment whose checksum verifies");
        assert_eq!(segment.source_port, MANAGEMENT_PORT);
        assert_eq!(segment.destination_port, self.port);
        self.expect = segment.sequence.add(segment.sequence_length());
        (
            segment.flags,
            segment.acknowledgement,
            segment.payload.to_vec(),
        )
    }
}

/// The bare transport on the management port, for the server's own tests: they
/// drive it directly, because a refusal the endpoint's own flow control makes
/// unreachable is one only a direct call reaches.
fn tcp_stack() -> lfw_tcp::TcpStack<TCP_CONNECTIONS> {
    lfw_tcp::TcpStack::new(
        OUR_ADDRESS,
        MANAGEMENT_PORT,
        TCP_MSS,
        REQUEST_CAPACITY as u32,
        secret(),
    )
}

/// Open one connection on `stack` as far as `SYN_RECEIVED`, answering its handle.
fn open(
    stack: &mut lfw_tcp::TcpStack<TCP_CONNECTIONS>,
    port: u16,
    out: &mut [u8],
) -> lfw_tcp::ConnectionId {
    let mut station = Station::new(port, u32::from(port) * 0x1000);
    let frame = station.frame(lfw_tcp::Flags::SYN, &[]);
    let ethernet = Ethernet::parse(&frame).expect("a frame");
    let packet = Ipv4Packet::parse(ethernet.payload).expect("a datagram");
    stack
        .receive(at(0), STATION_ADDRESS, packet.payload(), out)
        .connection
        .expect("a connection")
}

/// The window a frame's segment advertises.
fn window_of(frame: &[u8]) -> u16 {
    let ethernet = Ethernet::parse(frame).expect("a frame");
    let packet = Ipv4Packet::parse(ethernet.payload).expect("a datagram");
    lfw_tcp::Segment::parse(OUR_ADDRESS, STATION_ADDRESS, packet.payload())
        .expect("a segment")
        .window
}

/// A scrape request as a client puts one on the wire.
const SCRAPE: &[u8] = b"GET /metrics HTTP/1.1\r\nHost: 10.0.2.15\r\nUser-Agent: probe\r\n\r\n";

/// Take one connection from `SYN` to `ESTABLISHED`.
fn handshake(endpoint: &mut Endpoint, station: &mut Station, out: &mut [u8]) {
    let syn = station.frame(lfw_tcp::Flags::SYN, &[]);
    let len = endpoint
        .handle(Some(at(0)), &syn, out)
        .reply()
        .expect("a SYN-ACK");
    let (flags, _, _) = station.read(&out[..len]);
    assert!(flags.contains(lfw_tcp::Flags::SYN) && flags.contains(lfw_tcp::Flags::ACK));
    let ack = station.frame(lfw_tcp::Flags::ACK, &[]);
    endpoint.handle(Some(at(0)), &ack, out);
}

/// What one whole request/response exchange produced.
struct Answered {
    /// Every response byte, head and body, in the order the segments carried
    /// them.
    bytes: Vec<u8>,
    /// How many segments carried them.
    segments: usize,
    /// Whether the appliance closed its half, as `Connection: close` obliges.
    closed: bool,
    /// Whether it reset instead, which is what says a body is short of the
    /// length its head announced.
    reset: bool,
}

impl Answered {
    /// The head and body, split at the blank line. Parsed rather than matched:
    /// the response is what a client reads, so a test reads it the same way.
    fn split(&self) -> (String, &[u8]) {
        let at = self
            .bytes
            .windows(4)
            .position(|window| window == b"\r\n\r\n")
            .expect("a response head ends");
        let head = String::from_utf8(self.bytes[..at + 4].to_vec()).expect("an ASCII head");
        (head, &self.bytes[at + 4..])
    }

    fn status_line(&self) -> String {
        self.split()
            .0
            .lines()
            .next()
            .expect("a status line")
            .to_owned()
    }

    /// The value of one header field, matched case-insensitively.
    fn header(&self, name: &str) -> Option<String> {
        self.split().0.lines().skip(1).find_map(|line| {
            let (key, value) = line.split_once(": ")?;
            key.eq_ignore_ascii_case(name).then(|| value.to_owned())
        })
    }
}

/// One request in flight over an established connection, stepped the way a
/// protection domain steps one.
///
/// The three steps are separate calls rather than one loop because a test needs
/// to stand between them: a supplier that has *not* answered is exactly what
/// [`Transfer::drain`] with nothing supplied in front of it is, and a driver
/// that fetched the window itself could never produce that state.
struct Transfer<'a> {
    station: &'a mut Station,
    out: Vec<u8>,
    clock: u64,
    answered: Answered,
}

impl<'a> Transfer<'a> {
    /// Put `request` on an already-established connection and take whatever the
    /// frame itself provoked.
    fn begin(endpoint: &mut Endpoint, station: &'a mut Station, request: &[u8]) -> Self {
        let data = station.frame(lfw_tcp::Flags::ACK.with(lfw_tcp::Flags::PSH), request);
        let mut transfer = Self {
            station,
            out: vec![0u8; ROOMY],
            clock: 1_000,
            answered: Answered {
                bytes: Vec::new(),
                segments: 0,
                closed: false,
                reset: false,
            },
        };
        let reply = endpoint
            .handle(Some(at(transfer.clock)), &data, &mut transfer.out)
            .reply();
        transfer.take(reply);
        transfer
    }

    /// Read one frame the endpoint composed, if it composed one.
    fn take(&mut self, reply: Option<usize>) {
        let Some(len) = reply else {
            return;
        };
        let (flags, _, payload) = self.station.read(&self.out[..len]);
        if !payload.is_empty() {
            self.answered.segments += 1;
            self.answered.bytes.extend_from_slice(&payload);
        }
        self.answered.closed |= flags.contains(lfw_tcp::Flags::FIN);
        self.answered.reset |= flags.contains(lfw_tcp::Flags::RST);
    }

    /// Drive [`Endpoint::poll_output`] until the pass has nothing left, which is
    /// what a caller woken by one frame does so a response does not advance one
    /// segment per round trip.
    fn drain(&mut self, endpoint: &mut Endpoint) {
        for _ in 0..256 {
            self.clock += 1;
            let polled = endpoint.poll_output(at(self.clock), &mut self.out);
            if !polled.goes_on() {
                return;
            }
            self.take(polled.frame());
        }
        panic!("a pass never stopped producing");
    }

    /// Let the peer acknowledge what it has read, which is what opens the
    /// transport's window again.
    fn acknowledge(&mut self, endpoint: &mut Endpoint) {
        self.clock += 1;
        let ack = self.station.frame(lfw_tcp::Flags::ACK, &[]);
        let reply = endpoint
            .handle(Some(at(self.clock)), &ack, &mut self.out)
            .reply();
        self.take(reply);
    }
}

/// Send `request` and collect everything the endpoint answers, acknowledging as
/// a client does, until the appliance closes.
///
/// The loop is what a caller in a protection domain does: supply whatever the
/// body is, drive [`Endpoint::poll_output`] until the pass has nothing left,
/// supply again — a pass that produced nothing is a recording asking for its
/// next window — and let the peer's acknowledgement open the window.
fn exchange(
    endpoint: &mut Endpoint,
    station: &mut Station,
    supply: Supply,
    request: &[u8],
) -> Answered {
    let mut transfer = Transfer::begin(endpoint, station, request);
    for _ in 0..2048 {
        supply.offer(endpoint);
        transfer.drain(endpoint);
        if transfer.answered.closed {
            return transfer.answered;
        }
        supply.offer(endpoint);
        transfer.acknowledge(endpoint);
    }
    panic!("the appliance never finished answering");
}

/// A `GET` for `target`, as a client puts one on the wire.
fn get(target: &str) -> Vec<u8> {
    format!("GET {target} HTTP/1.1\r\nHost: 10.0.2.15\r\nUser-Agent: probe\r\n\r\n").into_bytes()
}

/// The exchange the end-to-end gate performs, driven here through the endpoint's
/// own surface: a handshake, a scrape answered over several segments, and a
/// close this end initiates.
#[test]
fn a_whole_http_exchange_crosses_the_endpoint() {
    let mut endpoint = endpoint();
    let mut station = Station::new(40000, 0x1234_5678);
    let mut out = vec![0u8; ROOMY];
    handshake(&mut endpoint, &mut station, &mut out);
    assert_eq!(endpoint.connections(), 1);

    let answered = exchange(&mut endpoint, &mut station, Supply::Rendered(BODY), SCRAPE);
    assert_eq!(answered.status_line(), "HTTP/1.1 200 OK");
    assert_eq!(
        answered.header("content-type").as_deref(),
        Some(lfw_http::METRICS_CONTENT_TYPE)
    );
    let (head, body) = answered.split();
    assert_eq!(body, BODY.bytes(), "the body is not what was rendered");
    assert_eq!(
        answered.header("content-length"),
        Some(body.len().to_string()),
        "the stated length is not the body's"
    );
    assert!(head.contains("Connection: close\r\n"));
    assert!(
        answered.segments > 1,
        "a {}-byte body arrived in one segment",
        body.len()
    );
    assert!(answered.closed, "Connection: close obliges a FIN");

    let counters = endpoint.http_counters();
    assert_eq!(counters.requests, 1);
    assert_eq!(counters.responses[lfw_http::Status::Ok.slot()], 1);
    assert_eq!(counters.response_bytes, answered.bytes.len() as u64);
    assert_eq!(counters.bodies_refused, 0);
    assert_eq!(counters.retransmits_unavailable, 0);

    // The station closes its own half, and the connection's whole state goes
    // with it — table slot, return path and response buffer together.
    let fin = station.frame(lfw_tcp::Flags::FIN.with(lfw_tcp::Flags::ACK), &[]);
    let outcome = endpoint.handle(Some(at(9_000)), &fin, &mut out);
    if let Some(len) = outcome.reply() {
        station.read(&out[..len]);
    }
    let mut settled = 0;
    let far = at(9_000 + lfw_tcp::TIME_WAIT_DURATION.as_nanos() + 1);
    while endpoint.connections() > 0 {
        settled += 1;
        assert!(settled <= 64, "the connection never closed");
        if !endpoint.poll_timeouts(far, &mut out).goes_on() && endpoint.connections() > 0 {
            break;
        }
    }
    assert_eq!(endpoint.connections(), 0);
    assert!(endpoint.paths.iter().all(Option::is_none));
    // The buffer is free again, so a second connection is answered 200 rather
    // than 503 — which is what proves the release happened.
    let mut second = Station::new(40001, 0x2222_0000);
    handshake(&mut endpoint, &mut second, &mut out);
    let again = exchange(&mut endpoint, &mut second, Supply::Rendered(BODY), SCRAPE);
    assert_eq!(again.status_line(), "HTTP/1.1 200 OK");
    assert_eq!(endpoint.http_counters().requests, 2);
    assert_eq!(
        endpoint.http_counters().responses[lfw_http::Status::Ok.slot()],
        2
    );
}

