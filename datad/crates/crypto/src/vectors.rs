//! Published cryptographic test vectors, as data.
//!
//! One source of truth for two consumers: the host tests in this crate, and
//! the cryptography protection domain, which re-runs every table at bring-up
//! on the shipped image and reports what answered. A second copy would be a
//! second thing to drift, and an appliance proving different vectors from the
//! ones the developer ran would prove the wrong thing.
//!
//! # Where each table comes from
//!
//! Each table's own comment records its provenance. The published sources are
//! the NIST Cryptographic Algorithm Validation Program's response files, RFC
//! 8439, and Project Wycheproof — the first two being what the specifications
//! themselves publish, the third being the adversarial set the specifications
//! do not carry. Nothing here was written by hand: the tables were emitted
//! from those files by a one-off generator that re-derived every expected
//! value with an independent implementation before writing it, so a
//! transcription error could not survive generation.
//!
//! # Why a curated subset and not the whole corpus
//!
//! The published files run to megabytes and the appliance re-runs these on
//! every boot, so the whole corpus would cost image size and boot time for
//! vectors that repeat one another. What is kept instead is the adversarial
//! shape of each: the boundary lengths where a padding or block loop changes
//! behaviour, the empty inputs, the keys either side of a hash block, and —
//! for every construction that authenticates — the forgeries a verifier must
//! refuse, which the NIST files largely do not carry and Wycheproof exists to
//! supply.
//!
//! # Adversary
//!
//! None. These are build-time constants compared against this crate's own
//! output; no byte here comes from a device, a peer protection domain or the
//! network. The `authentic: false` rows model an adversary's forgery, but
//! they arrive as constants like every other row.

/// A hash function's answer for one message.
pub struct HashVector {
    /// Where the row came from, carried onto a failure so a mismatch names the
    /// published row it disagrees with rather than an index into this file.
    pub id: &'static str,
    pub message: &'static [u8],
    pub digest: [u8; 32],
}

/// A message authentication code's answer, and whether it is the authentic one.
pub struct MacVector {
    pub id: &'static str,
    pub key: &'static [u8],
    pub message: &'static [u8],
    pub tag: [u8; 32],
    /// `false` on a forgery, which a verifier must refuse.
    pub authentic: bool,
}

/// A key derivation's output for one salt, keying material and context.
pub struct KdfVector {
    pub id: &'static str,
    pub ikm: &'static [u8],
    pub salt: &'static [u8],
    pub info: &'static [u8],
    pub okm: &'static [u8],
}

/// One authenticated encryption case. `plaintext` is empty on a refusing row:
/// a forgery has no plaintext to reveal, and a row that carried one would
/// invite a test that decrypted it anyway.
pub struct AeadVector {
    pub id: &'static str,
    pub key: [u8; 32],
    pub nonce: [u8; 12],
    pub associated_data: &'static [u8],
    pub plaintext: &'static [u8],
    pub ciphertext: &'static [u8],
    pub tag: [u8; 16],
    /// `false` on a forgery, which an open must refuse.
    pub authentic: bool,
}

/// A stream cipher's keystream from a given key, nonce and block counter.
pub struct StreamVector {
    pub id: &'static str,
    pub key: [u8; 32],
    pub nonce: [u8; 12],
    pub counter: u32,
    pub keystream: &'static [u8],
}

/// The generator's first output for a fixed seed.
pub struct DrbgVector {
    pub id: &'static str,
    pub key: [u8; 32],
    pub nonce: [u8; 12],
    pub first_output: &'static [u8],
}

