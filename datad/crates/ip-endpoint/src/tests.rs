/// A recording several windows long, end to end: every byte arrives once, in
/// order, and what the client reassembles is the recording.
///
/// The counters are asserted exactly rather than loosely, because they are the
/// arithmetic the whole shape rests on: one supply per window, and one miss per
/// slide — the pass on which the endpoint discovered it had run out and sent
/// nothing.
#[test]
fn a_recording_several_windows_long_arrives_whole_and_in_order() {
    // Longer than the staging buffer by at least one whole window, derived from
    // the buffer rather than chosen: the shape under test is a body that *cannot*
    // have been staged whole, and a recording sized by a literal stops being one
    // the day the renderer's worst case — which is what sizes that buffer — grows.
    // The odd tail keeps the last window a partial one.
    let recording = Recording((RESPONSE_CAPACITY + WINDOW_LEN) as u64 + 777);
    let mut endpoint = streaming_endpoint();
    let mut station = Station::new(40000, 0x1234_0001);
    let mut out = vec![0u8; ROOMY];
    handshake(&mut endpoint, &mut station, &mut out);

    let answered = exchange(
        &mut endpoint,
        &mut station,
        Supply::Streamed(recording),
        &get(RECORDING_TARGET),
    );
    assert_eq!(answered.status_line(), "HTTP/1.1 200 OK");
    assert_eq!(
        answered.header("content-type").as_deref(),
        Some(ContentType::OctetStream.as_str())
    );
    assert_eq!(
        answered.header("content-length"),
        Some(recording.0.to_string()),
        "the stated length is not the recording's"
    );
    let (head, body) = answered.split();
    assert_eq!(body, recording.bytes(), "the recording did not survive");
    assert!(head.contains("Connection: close\r\n"));
    assert!(answered.closed, "Connection: close obliges a FIN");
    assert!(
        answered.bytes.len() > RESPONSE_CAPACITY,
        "the body was small enough to have been staged whole"
    );

    let counters = endpoint.http_counters();
    assert_eq!(counters.streams_started, 1);
    assert_eq!(counters.windows_supplied, recording.windows());
    assert!(
        counters.window_misses >= 1,
        "no pass ever ran out of window, so the shape under test was not exercised"
    );
    assert!(
        counters.window_misses < recording.windows(),
        "{} passes produced nothing for {} windows: a miss costs at most one \
         pass per slide, and a slide the peer's acknowledgement drives costs none",
        counters.window_misses,
        recording.windows()
    );
    assert_eq!(counters.windows_refused, 0);
    assert_eq!(counters.streams_abandoned, 0);
    assert_eq!(counters.retransmits_unavailable, 0);
    assert_eq!(counters.responses[lfw_http::Status::Ok.slot()], 1);
    assert_eq!(counters.response_bytes, answered.bytes.len() as u64);
}

