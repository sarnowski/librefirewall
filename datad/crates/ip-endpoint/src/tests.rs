/// The whole of the "not ready yet" contract: the endpoint asks for a window,
/// gets nothing, sends nothing, asks for the same window again on the next pass,
/// and picks up at exactly the byte it stopped at once the window arrives.
#[test]
fn a_window_the_caller_has_not_supplied_stops_the_pass_without_losing_its_place() {
    let recording = Recording(2 * WINDOW_LEN as u64);
    let mut endpoint = streaming_endpoint();
    let mut station = Station::new(40000, 0x5555_0001);
    let mut out = vec![0u8; ROOMY];
    handshake(&mut endpoint, &mut station, &mut out);

    let mut transfer = Transfer::begin(&mut endpoint, &mut station, &get(RECORDING_TARGET));
    // The first window, and then nothing more: the supplier stops answering.
    Supply::Streamed(recording).offer(&mut endpoint);
    for _ in 0..64 {
        transfer.drain(&mut endpoint);
        if endpoint.window_wanted().is_some() {
            break;
        }
        transfer.acknowledge(&mut endpoint);
    }
    let (_, wanted, _) = endpoint.window_wanted().expect("the window ran out");
    assert!(
        wanted > 0 && wanted < recording.0,
        "the second window starts at {wanted}"
    );
    let delivered = transfer.answered.bytes.len();
    let missed = endpoint.http_counters().window_misses;
    assert!(
        missed >= 1,
        "the pass that produced nothing was not counted"
    );

    // Three more passes with nothing supplied: nothing goes out, the same window
    // is asked for again, and the place is kept.
    for _ in 0..3 {
        transfer.drain(&mut endpoint);
        transfer.acknowledge(&mut endpoint);
        assert_eq!(
            transfer.answered.bytes.len(),
            delivered,
            "bytes went out with no window to send them from"
        );
        assert_eq!(
            endpoint.window_wanted().map(|(_, start, _)| start),
            Some(wanted),
            "the endpoint moved on from the window it asked for"
        );
    }
    assert!(
        endpoint.http_counters().window_misses > missed,
        "a pass that sent nothing was not counted as a miss"
    );

    // And once it arrives the transfer resumes where it stopped and completes.
    for _ in 0..2048 {
        Supply::Streamed(recording).offer(&mut endpoint);
        transfer.drain(&mut endpoint);
        if transfer.answered.closed {
            break;
        }
        Supply::Streamed(recording).offer(&mut endpoint);
        transfer.acknowledge(&mut endpoint);
    }
    assert!(transfer.answered.closed, "the transfer never finished");
    assert_eq!(transfer.answered.split().1, recording.bytes());
}

/// A window at an offset nobody asked for, and one of the wrong length, are both
/// refused and counted: taking either would put a recording's bytes at the wrong
/// place in a stream no client could check.
#[test]
fn a_window_that_was_not_asked_for_is_refused_and_counted() {
    let recording = Recording(3 * WINDOW_LEN as u64);
    let mut endpoint = streaming_endpoint();
    let mut station = Station::new(40000, 0x6666_0001);
    let mut out = vec![0u8; ROOMY];

    // Nothing is streaming at all, so there is no window to supply.
    assert!(!endpoint.supply_window(0, &[0u8; 8]));
    assert_eq!(endpoint.http_counters().windows_refused, 1);

    handshake(&mut endpoint, &mut station, &mut out);
    let data = station.frame(
        lfw_tcp::Flags::ACK.with(lfw_tcp::Flags::PSH),
        &get(RECORDING_TARGET),
    );
    endpoint.handle(Some(at(1_000)), &data, &mut out);
    assert!(endpoint.begin_stream(recording.0, ContentType::OctetStream));
    let (_, start, len) = endpoint.window_wanted().expect("a window is wanted");
    assert_eq!((start, len), (0, WINDOW_LEN));

    // An offset that was not asked for.
    assert!(!endpoint.supply_window(1, &recording.window(1, len)));
    // The right offset and nothing at all, which advances nothing and would
    // leave the transfer asking for the same window for ever.
    assert!(!endpoint.supply_window(0, &[]));
    // The right offset, one byte more than the array will take.
    let mut over = recording.window(0, len);
    over.push(0);
    assert!(!endpoint.supply_window(0, &over));
    assert_eq!(endpoint.http_counters().windows_refused, 4);
    assert_eq!(endpoint.http_counters().windows_supplied, 0);

    // And the one it did ask for is taken, so the refusals changed nothing.
    assert!(endpoint.supply_window(0, &recording.window(0, len)));
    assert_eq!(endpoint.http_counters().windows_supplied, 1);
}

/// Abandoning part way ends the connection short of the length the head
/// announced — no padding — with a `RST` rather than a `FIN`: a truncated body
/// closed in an orderly way reads to an intermediary as a complete one. The
/// staging buffer comes back, which the next scrape being answered `200` rather
/// than `503` is what proves.
#[test]
fn abandoning_a_recording_resets_short_and_frees_the_buffer() {
    let recording = Recording(4 * WINDOW_LEN as u64);
    let mut endpoint = streaming_endpoint();
    let mut station = Station::new(40000, 0x7777_0001);
    let mut out = vec![0u8; ROOMY];
    handshake(&mut endpoint, &mut station, &mut out);

    let mut transfer = Transfer::begin(&mut endpoint, &mut station, &get(RECORDING_TARGET));
    Supply::Streamed(recording).offer(&mut endpoint);
    transfer.drain(&mut endpoint);
    transfer.acknowledge(&mut endpoint);
    let sent = transfer.answered.bytes.len();
    assert!(sent > 0, "nothing had gone out to abandon");

    endpoint.abandon_stream();
    assert_eq!(endpoint.http_counters().streams_abandoned, 1);
    for _ in 0..64 {
        transfer.drain(&mut endpoint);
        if transfer.answered.reset {
            break;
        }
        transfer.acknowledge(&mut endpoint);
    }
    assert!(transfer.answered.reset, "the connection was not reset");
    assert!(
        !transfer.answered.closed,
        "a truncated body was ended with an orderly close"
    );
    let (head, body) = transfer.answered.split();
    assert!(head.contains(&format!("Content-Length: {}\r\n", recording.0)));
    assert!(
        (body.len() as u64) < recording.0,
        "the body was padded out to the length it announced"
    );
    assert_eq!(
        body,
        &recording.bytes()[..body.len()],
        "the bytes that did arrive were not the recording's"
    );

    // The buffer is free again, so the next scrape is answered rather than 503.
    let mut second = Station::new(40001, 0x7788_0001);
    handshake(&mut endpoint, &mut second, &mut out);
    let again = exchange(&mut endpoint, &mut second, Supply::Rendered(BODY), SCRAPE);
    assert_eq!(again.status_line(), "HTTP/1.1 200 OK");
}

